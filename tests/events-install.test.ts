describe('json-nested (Claude)', () => {
  test('merge into empty file', () => {
    const manifest = fakeManifest();
    const created = installIntegrationEvents(new ClaudeIntegration(), tmp, manifest, {
      pre_tool_use: [{ command: 'speckit.tdd.validate', matcher: 'Edit|Write' }],
    });
    const data = readJson('.claude/settings.json');
    expect(data.hooks.PreToolUse[0].matcher).toBe('Edit|Write');
    const inner = data.hooks.PreToolUse[0].hooks[0];
    expect(typeof inner.command).toBe('string');
    expect(inner.args).toBeUndefined();
    expect(inner.command).toBe('python3 "${CLAUDE_PROJECT_DIR}/.specify/events.py" speckit.tdd.validate pre_tool_use 60');
    expect(inner.timeout).toBe(65);
    expect(inner.__speckit_event__).toBe(true);
    // Dispatcher generated byte-identical and executable.
    const dispatcher = path.join(tmp, EVENTS_DISPATCHER_REL);
    expect(readFileSync(dispatcher, 'utf8')).toBe(EVENTS_DISPATCHER_TEMPLATE);
    expect(statSync(dispatcher).mode & 0o777).toBe(0o755);
    expect(manifest.calls.recordFile).toEqual(['.specify/events.py']);
    expect(manifest.calls.recordExisting).toEqual(['.claude/settings.json']);
    expect(created).toEqual([dispatcher, path.join(tmp, '.claude/settings.json')]);
    // Python json.dumps(indent=2) layout
    expect(readFileSync(path.join(tmp, '.claude/settings.json'), 'utf8')).toBe(
      '{\n  "hooks": {\n    "PreToolUse": [\n      {\n        "matcher": "Edit|Write",\n        "hooks": [\n          {\n' +
        '            "type": "command",\n            "command": "python3 \\"${CLAUDE_PROJECT_DIR}/.specify/events.py\\" speckit.tdd.validate pre_tool_use 60",\n' +
        '            "timeout": 65,\n            "__speckit_event__": true\n          }\n        ]\n      }\n    ]\n  }\n}\n',
    );
  });

  test('all handlers for the same event are emitted (#2)', () => {
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), {
      pre_tool_use: [{ command: 'speckit.tdd.validate' }, { command: 'speckit.other.check' }],
    });
    const cmds = readJson('.claude/settings.json').hooks.PreToolUse.flatMap((g: any) =>
      g.hooks.map((h: any) => h.command),
    );
    expect(cmds.some((c: string) => c.includes('speckit.tdd.validate'))).toBe(true);
    expect(cmds.some((c: string) => c.includes('speckit.other.check'))).toBe(true);
  });

  test('matcher grouping per distinct matcher (S3)', () => {
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), {
      pre_tool_use: [
        { command: 'speckit.first', matcher: 'Edit' },
        { command: 'speckit.second', matcher: 'Bash' },
        { command: 'speckit.third', matcher: 'Edit' },
      ],
    });
    const groups = readJson('.claude/settings.json').hooks.PreToolUse;
    expect(groups.map((g: any) => g.matcher)).toEqual(['Edit', 'Bash']);
    expect(groups[0].hooks).toHaveLength(2);
    expect(groups[1].hooks[0].command).toContain('speckit.second');
  });

  test('remove preserves user hooks', () => {
    write(
      '.claude/settings.json',
      JSON.stringify({
        hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: 'user-check' }] }] },
        userSetting: true,
      }),
    );
    const manifest = fakeManifest();
    installIntegrationEvents(new ClaudeIntegration(), tmp, manifest, { stop: [{ command: 'speckit.end' }] });
    removeIntegrationEvents(new ClaudeIntegration(), tmp, manifest);
    const data = readJson('.claude/settings.json');
    expect(data.userSetting).toBe(true);
    expect(data.hooks.Stop).toBeUndefined();
    expect(data.hooks.PreToolUse[0].matcher).toBe('Bash');
    expect(manifest.calls.remove).toContain('.claude/settings.json');
  });

  test('upgrade does not duplicate nested hooks (#9) and stale events are removed (#11)', () => {
    const events = { pre_tool_use: [{ command: 'speckit.tdd.validate' }] };
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), events);
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), events);
    const groups = readJson('.claude/settings.json').hooks.PreToolUse;
    expect(groups).toHaveLength(1);
    expect(groups[0].hooks).toHaveLength(1);

    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), { stop: [{ command: 'speckit.end' }] });
    const hooks = readJson('.claude/settings.json').hooks;
    expect(hooks.PreToolUse).toBeUndefined();
    expect(hooks.Stop).toBeDefined();
  });

  test('empty events strip prior hooks (#3) and delete Spec-Kit-only config (#14)', () => {
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), {
      pre_tool_use: [{ command: 'speckit.tdd.validate' }],
    });
    expect(existsSync(path.join(tmp, '.claude/settings.json'))).toBe(true);
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), {});
    expect(existsSync(path.join(tmp, '.claude/settings.json'))).toBe(false);
    // No other integration references the dispatcher → removed too (S3).
    expect(existsSync(path.join(tmp, EVENTS_DISPATCHER_REL))).toBe(false);
  });

  test('JSONC config is not reset and not tracked (#22, S5)', () => {
    const jsonc = '{\n  // my comment\n  "hooks": {}\n}\n';
    write('.claude/settings.json', jsonc);
    const manifest = fakeManifest();
    const created = installIntegrationEvents(new ClaudeIntegration(), tmp, manifest, {
      pre_tool_use: [{ command: 'speckit.tdd.validate' }],
    });
    expect(readFileSync(path.join(tmp, '.claude/settings.json'), 'utf8')).toBe(jsonc);
    expect(manifest.calls.recordExisting).toEqual([]);
    expect(created).toEqual([path.join(tmp, EVENTS_DISPATCHER_REL)]);
    expect(String(stderrSpy.mock.calls.map((c: unknown[]) => c[0]).join(''))).toContain(
      'skipping event-config merge to preserve user content.',
    );
  });

  test('unreadable config (a directory) aborts the merge', () => {
    mkdirSync(path.join(tmp, '.claude/settings.json'), { recursive: true });
    installIntegrationEvents(new ClaudeIntegration(), tmp, fakeManifest(), {
      pre_tool_use: [{ command: 'speckit.tdd.validate' }],
    });
    expect(statSync(path.join(tmp, '.claude/settings.json')).isDirectory()).toBe(true);
  });

  test('forced full teardown with a real manifest preserves user config (S9)', () => {
    write(
      '.claude/settings.json',
      JSON.stringify({
        hooks: { PreToolUse: [{ matcher: 'Bash', hooks: [{ type: 'command', command: 'user-check' }] }] },
        userSetting: true,
      }),
    );
    const integration = new ClaudeIntegration();
    const manifest = new IntegrationManifest('claude', tmp, 'test');
    installIntegrationEvents(integration, tmp, manifest, { stop: [{ command: 'speckit.end' }] });
    manifest.save();
    expect(Object.keys(manifest.files)).toContain('.specify/events.py');
    removeIntegrationEvents(integration, tmp, manifest);
    manifest.uninstall(tmp, { force: true });
    const data = readJson('.claude/settings.json');
    expect(data.userSetting).toBe(true);
    expect(data.hooks.PreToolUse[0].matcher).toBe('Bash');
  });
});


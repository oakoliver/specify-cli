/** MagicMock(spec=IntegrationManifest) equivalent that records calls. */
function fakeManifest(): EventManifest & {
  files: Record<string, string>;
  calls: { recordFile: string[]; recordExisting: string[]; remove: string[] };
} {
  const calls = { recordFile: [] as string[], recordExisting: [] as string[], remove: [] as string[] };
  return {
    files: {},
    calls,
    recordFile(rel: string) {
      calls.recordFile.push(rel);
    },
    recordExisting(rel: string) {
      calls.recordExisting.push(rel);
    },
    remove(rel: string) {
      calls.remove.push(rel);
    },
  };
}

function readJson(rel: string): any {
  return JSON.parse(readFileSync(path.join(tmp, rel), 'utf8'));
}

function write(rel: string, content: string | Buffer): string {
  const p = path.join(tmp, rel);
  mkdirSync(path.dirname(p), { recursive: true });
  writeFileSync(p, content);
  return p;
}

